import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('artifacts',{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.TEST_URL||'http://127.0.0.1:4173');
await page.locator('#status').filter({hasText:'Search 81,343 songs'}).waitFor({timeout:60000});
await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
await page.locator('#search').fill('Radiohead');
await page.locator('[data-result="0"]').waitFor();
await page.locator('[data-result="0"]').click();
await page.locator('.track').first().waitFor();
assert.equal(await page.locator('.track').count(),24);
await page.locator('#bpm-min').fill('50');await page.locator('#bpm-max').fill('90');
await page.locator('#mood').selectOption('Melancholic');
await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Ranked'));
await page.waitForTimeout(400);
for(const el of await page.locator('.bpm').all()){const bpm=parseInt(await el.innerText());assert.ok(bpm>=50&&bpm<=90);}
for(const el of await page.locator('.track .tags').all())assert.match(await el.innerText(),/Melancholic/);
await page.locator('#voice').selectOption('female');await page.waitForTimeout(400);
assert.ok(await page.locator('.track').count()>0);
await page.locator('[data-save="0"]').click();assert.equal(await page.locator('#saved-count').textContent(),'1');
await page.locator('#saved-nav').click();assert.equal(await page.locator('.track').count(),1);
await page.reload();await page.locator('#saved-nav').click();assert.equal(await page.locator('.track').count(),1);
await page.locator('#about').click();await page.locator('#info[open]').waitFor();await page.locator('.dialog-close').click();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.locator('#search').fill('zzzzznonexistenttrackzzzzz');
await page.locator('#suggestions').filter({hasText:'No match'}).waitFor();
assert.deepEqual(errors,[]);
console.log('Browser checks passed: catalogue, search, recommendations, BPM, mood, vocals, save, persistence, dialog, mobile overflow, empty search.');
await browser.close();
